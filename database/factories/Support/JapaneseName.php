    {
        for ($try = 0; $try < 1000; $try++) {
            [$family, $familyKana] = fake()->randomElement(self::FAMILY);
            [$given, $givenKana] = fake()->randomElement(self::GIVEN);

            if (! isset(self::$used[$family.$given])) {
                self::$used[$family.$given] = true;

                return [$family.$separator.$given, $familyKana.$separator.$givenKana];
            }
        }

        // 組み合わせを使い切ったとき（約 4,800 通りあるので、ふつうは起きない）
        throw new \RuntimeException('名前の組み合わせが足りません。JapaneseName に姓・名を追加してください。');
